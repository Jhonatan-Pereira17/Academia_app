CREATE TABLE physical_evaluations (
    id BIGSERIAL PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    personal_id BIGINT NOT NULL REFERENCES personals(id),
    evaluation_date DATE NOT NULL,
    weight_kg NUMERIC(5,2),
    height_cm NUMERIC(5,1),
    body_fat_percentage NUMERIC(4,1),
    muscle_mass_kg NUMERIC(5,2),
    arm_cm NUMERIC(5,1),
    chest_cm NUMERIC(5,1),
    waist_cm NUMERIC(5,1),
    hip_cm NUMERIC(5,1),
    thigh_cm NUMERIC(5,1),
    calf_cm NUMERIC(5,1),
    skinfold_triceps_mm NUMERIC(4,1),
    skinfold_subscapular_mm NUMERIC(4,1),
    skinfold_chest_mm NUMERIC(4,1),
    skinfold_axillary_mm NUMERIC(4,1),
    skinfold_suprailiac_mm NUMERIC(4,1),
    skinfold_abdominal_mm NUMERIC(4,1),
    skinfold_thigh_mm NUMERIC(4,1),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_physical_evaluations_student_date UNIQUE (student_id, evaluation_date)
);